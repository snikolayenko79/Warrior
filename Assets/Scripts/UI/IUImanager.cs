using UnityEngine;

public interface IUIManager
{
    /// <summary>
    /// Полностью очищает текущий экран и всю историю открытых всплывающих окон (стек).
    /// Обычно вызывается автоматически при смене сцен.
    /// </summary>
    void ClearCurrentUI();

    /// <summary>
    /// Открывает модальное всплывающее окно (попап) поверх текущего экрана.
    /// Предыдущий экран автоматически блокируется и сохраняется в историю.
    /// </summary>
    /// <param name="popupPrefab">Префаб окна, содержащий компонент UIScreenView.</param>
    /// <returns>Экземпляр созданного окна типа UIView.</returns>
    IUIView OpenPopup(IUIView popupPrefab);

    /// <summary>
    /// Закрывает текущее активное верхнее окно. 
    /// Если в истории (стеке) есть предыдущие окна, они автоматически разблокируются.
    /// Если окон в истории нет, но мы находимся в игре — активирует меню паузы.
    /// </summary>
    void CloseCurrentPopup();
}